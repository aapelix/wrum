CREATE TABLE players (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  country TEXT NOT NULL DEFAULT 'FI',
  token_hash BYTEA NOT NULL UNIQUE,
  created_at BIGINT NOT NULL
);
CREATE UNIQUE INDEX players_name_ci ON players (lower(name));

CREATE TABLE results (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  level TEXT NOT NULL,
  position INT NOT NULL,
  players_in_race INT NOT NULL,
  total_time REAL,
  best_lap REAL,
  at BIGINT NOT NULL
);
CREATE INDEX results_player ON results(player_id);

CREATE TABLE records (
  player_id BIGINT NOT NULL REFERENCES players(id) ON DELETE CASCADE,
  level TEXT NOT NULL,
  best_lap REAL,
  best_total REAL,
  PRIMARY KEY (player_id, level)
);
CREATE INDEX rec_lap ON records(level, best_lap);
CREATE INDEX rec_total ON records(level, best_total);
